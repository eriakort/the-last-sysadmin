// Pure scheduling tests for the Network Trainer spaced-recall model.
const assert = require('assert');
const R = require('./net-spaced-recall');
const now = 1000000000;
const guide = command => command === 'show ip route' ? { challenge: 'route?', answer: 'routing table' } : null;
let state = R.add({}, 'show ip route', now);
assert.strictEqual(state['show ip route'].dueAt, now + R.DAY_MS);
assert.strictEqual(R.dueCount(state, now), 0);
assert.strictEqual(R.dueCount(state, now + R.DAY_MS), 1);
assert.strictEqual(R.items(state, guide, now + R.DAY_MS)[0].command, 'show ip route');
assert.strictEqual(R.items(state, guide, now).length, 1);
const duplicate = R.add(state, 'show ip route', now + 5000);
assert.strictEqual(duplicate['show ip route'].dueAt, state['show ip route'].dueAt, 'adding an existing card must not reset its schedule');
state = R.review(state, 'show ip route', true, now + R.DAY_MS);
assert.strictEqual(state['show ip route'].stage, 1);
assert.strictEqual(state['show ip route'].reviews, 1);
assert.strictEqual(state['show ip route'].dueAt, now + 4 * R.DAY_MS);
assert.strictEqual(state['show ip route'].lastResult, 'recalled');
state = R.review(state, 'show ip route', false, now + 4 * R.DAY_MS);
assert.strictEqual(state['show ip route'].stage, 0);
assert.strictEqual(state['show ip route'].lapses, 1);
assert.strictEqual(state['show ip route'].dueAt, now + 5 * R.DAY_MS);
assert.strictEqual(state['show ip route'].lastResult, 'needs-practice');
assert.strictEqual(R.review(state, 'missing command', true, now), null);
assert.strictEqual(R.add(state, '', now)[''].dueAt, undefined);
const malformed = { bad: { dueAt: 'not-a-date' }, unknown: { dueAt: now } };
assert.strictEqual(R.items(malformed, guide, now).length, 0, 'malformed and unknown concepts are ignored');
assert.strictEqual(state['show ip route'].dueAt, now + 5 * R.DAY_MS, 'operations must not mutate input state');
console.log('NETWORK SPACED RECALL MODEL OK.');
