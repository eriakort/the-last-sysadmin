// Modal and search-palette accessibility: semantics, focus containment, Escape and restoration.
const path=require('path');
const {chromium}=require('playwright');
const URL='file://'+path.join(process.cwd(),'index.html')+'?view=workbench';
(async()=>{
 const browser=await chromium.launch(),page=await browser.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const ok=m=>console.log('  ✓ '+m),fail=m=>{console.error('  ✗ '+m);errors.push(m);};
 await page.goto(URL,{waitUntil:'load'});await page.waitForTimeout(200);
 await page.locator('#btnSet').focus();await page.keyboard.press('Enter');
 const dialog=page.locator('#modal [role=dialog]');
 if(await dialog.count()===1&&await dialog.getAttribute('aria-modal')==='true'&&await dialog.getAttribute('aria-labelledby'))ok('settings exposes a labelled modal dialog');
 else fail('settings dialog semantics or accessible name missing');
 if(await page.evaluate(()=>document.activeElement?.id)==='closeS')ok('opening a modal moves focus to its close action');
 else fail('settings did not receive initial focus');
 await page.keyboard.press('Shift+Tab');
 if(await page.evaluate(()=>document.activeElement?.id)==='reset')ok('Shift+Tab moves to the preceding settings action');
 else fail('Shift+Tab did not move to the preceding settings action');
 await page.keyboard.press('Shift+Tab');
 if(await page.evaluate(()=>document.activeElement?.id)==='closeS')ok('Shift+Tab wraps from the first action to the last');
 else fail('modal focus did not wrap backwards');
 await page.keyboard.press('Escape');
 if(await page.locator('#modal').count()===0&&await page.evaluate(()=>document.activeElement?.id)==='btnSet')ok('Escape closes the dialog and restores focus to its opener');
 else fail('Escape or focus restoration failed for settings');
 await page.locator('#btnQueue').focus();await page.keyboard.press('Enter');
 if(await page.locator('#modal [role=dialog][aria-modal=true][aria-labelledby]').count()===1)ok('incident queue uses the shared modal interaction contract');
 else fail('incident queue is missing shared dialog semantics');
 for(let i=0;i<5;i++)await page.keyboard.press('Tab');
 if(await page.evaluate(()=>!!document.querySelector('#modal')?.contains(document.activeElement)))ok('Tab navigation remains contained within the incident queue');
 else fail('Tab escaped the incident queue');
 await page.keyboard.press('Escape');
 if(await page.locator('#modal').count()===0&&await page.evaluate(()=>document.activeElement?.id)==='btnQueue')ok('queue Escape dismissal restores focus');
 else fail('queue focus restoration failed');
 await page.locator('#btnSearch').focus();await page.keyboard.press('Enter');
 if(await page.locator('#workstationPalette [role=dialog][aria-modal=true]').count()===1&&await page.locator('#paletteSearch').getAttribute('aria-label'))ok('search palette has modal semantics and a named search input');
 else fail('search palette semantics or search name missing');
 await page.keyboard.press('Tab');await page.keyboard.press('Shift+Tab');
 if(await page.evaluate(()=>document.querySelector('#workstationPalette')?.contains(document.activeElement)))ok('search palette traps forward and reverse Tab navigation');
 else fail('search palette focus escaped');
 await page.keyboard.press('Escape');
 if(await page.locator('#workstationPalette').count()===0&&await page.evaluate(()=>document.activeElement?.id)==='btnSearch')ok('search palette restores focus to its launcher');
 else fail('search palette focus restoration failed');
 await browser.close();
 if(errors.length){console.error('\\nMODAL ACCESSIBILITY UI TEST FAILED ('+errors.length+')');process.exit(1);}
 console.log('\\nMODAL ACCESSIBILITY UI OK.');
})();