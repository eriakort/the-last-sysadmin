const path = require('path');
const { chromium } = require('playwright');
const URL = 'file://' + path.join(process.cwd(), 'index.html?view=workbench');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(URL, { waitUntil: 'load' });
  await page.click('#btnBuild');
  await page.waitForSelector('#config .pal[data-add="host"]');
  await page.click('#config .pal[data-add="host"]');
  await page.click('#config .pal[data-add="host"]');
  await page.waitForFunction(() => document.querySelectorAll('#topo .node').length === 2);
  const nodes = page.locator('#topo .node');
  // Disable the builder's default 24-unit snap grid so keyboard step assertions measure the configured 10/40-unit movement precisely.
  if (await page.locator('#snapBtn').getAttribute('aria-pressed') === 'true') await page.click('#snapBtn');
  const firstId = await nodes.nth(0).getAttribute('data-dev');
  const secondId = await nodes.nth(1).getAttribute('data-dev');
  const position = async id => {
    const transform = await page.locator('#topo .node[data-dev="'+id+'"]').getAttribute('transform');
    const match = /translate\(([-\d.]+),\s*([-\d.]+)\)/.exec(transform || '');
    if (!match) throw new Error('Device transform is missing for '+id);
    return [Number(match[1]), Number(match[2])];
  };
  const beforeMove = await position(firstId);
  await nodes.nth(0).focus();
  await page.keyboard.press('Alt+ArrowRight');
  const afterMove = await position(firstId);
  if (afterMove[0] - beforeMove[0] !== 10 || afterMove[1] !== beforeMove[1]) throw new Error('Alt+ArrowRight did not move the device by the normal 10-unit step');
  if (!(await page.locator('#topo .node[data-dev="'+firstId+'"]').evaluate(el=>el===document.activeElement))) throw new Error('Device focus was not restored after normal keyboard movement');
  await page.keyboard.press('Shift+Alt+ArrowRight');
  const afterLargeMove = await position(firstId);
  if (afterLargeMove[0] - afterMove[0] !== 40 || afterLargeMove[1] !== afterMove[1]) throw new Error('Shift+Alt+ArrowRight did not move the device by the larger 40-unit step');
  if (!(await page.locator('#topo .node[data-dev="'+firstId+'"]').evaluate(el=>el===document.activeElement))) throw new Error('Device focus was not restored after large keyboard movement');
  await page.locator('#topo .node[data-dev="'+secondId+'"]').focus();
  await page.keyboard.press('Space');
  if (!(await page.locator('#topo .node[data-dev="'+secondId+'"]').evaluate(el=>el.classList.contains('sel')))) throw new Error('Space did not activate the focused device');
  await page.locator('#topo .node[data-dev="'+firstId+'"]').focus();
  await page.keyboard.press('c');
  await page.locator('#topo .node[data-dev="'+secondId+'"]').focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelectorAll('#topo .edge').length === 1);
  const edge=page.locator('#topo .edge').first();
  if(await edge.getAttribute('role')!=='button'||await edge.getAttribute('tabindex')!=='0'||!(await edge.getAttribute('aria-label')))throw new Error('Connection is not an accessible control');
  await edge.focus(); await page.keyboard.press('Enter');
  await page.locator('#topo .edge').first().focus(); await page.keyboard.press('Shift+F10');
  await page.waitForSelector('.topo-context-menu');
  const linkMenuItems=page.locator('.topo-context-menu [role="menuitem"]:not(:disabled)');
  if(await linkMenuItems.count()<1)throw new Error('Link context menu has no usable actions');
  await page.keyboard.press('Home');
  await page.keyboard.press('Escape');
  await page.waitForTimeout(50);
  const svg=page.locator('#topo');
  const edgeFocus=page.locator('#topo .edge').first();
  if(!(await edgeFocus.evaluate(el=>el===document.activeElement))) throw new Error('Link context menu did not restore focus');
  await page.once('dialog',d=>d.accept('Keyboard note'));
  await page.click('#noteBtn');
  const note=page.locator('#topo .topo-note').first();
  if(await note.getAttribute('role')!=='button'||await note.getAttribute('tabindex')!=='0'||!(await note.getAttribute('aria-label')))throw new Error('Note is not keyboard accessible');
  await note.focus(); await page.keyboard.press('Space');
  await page.waitForTimeout(50);
  await page.locator('#topo .topo-note').first().focus(); await page.keyboard.press('Shift+F10');
  await page.waitForSelector('.topo-context-menu'); await page.keyboard.press('Escape');
  if(!(await page.locator('#topo .topo-note').first().evaluate(el=>el===document.activeElement)))throw new Error('Note context menu did not restore focus');
  await page.click('[data-draw-tool="rect"]');
  const box=await page.locator('#topo').boundingBox();
  await page.mouse.move(box.x+box.width*.2,box.y+box.height*.65);await page.mouse.down();await page.mouse.move(box.x+box.width*.3,box.y+box.height*.75,{steps:3});await page.mouse.up();
  const drawing=page.locator('#topo .topo-drawing').first();
  if(await drawing.getAttribute('role')!=='button'||await drawing.getAttribute('tabindex')!=='0'||!(await drawing.getAttribute('aria-label')))throw new Error('Drawing is not keyboard accessible');
  await drawing.focus();await page.keyboard.press('Space');
  await drawing.focus();await page.keyboard.press('Shift+F10');
  await page.waitForSelector('.topo-context-menu');await page.keyboard.press('Escape');
  if(!(await page.locator('#topo .topo-drawing').first().evaluate(el=>el===document.activeElement)))throw new Error('Drawing context menu did not restore focus');
  if(errors.length)throw new Error(errors.join(' | '));
  await browser.close(); console.log('TOPOLOGY OBJECT KEYBOARD TEST OK');
})().catch(e=>{console.error(e);process.exit(1);});
