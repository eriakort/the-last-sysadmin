const path=require('path');
const {chromium}=require('playwright');
const URL='file://'+path.join(process.cwd(),'index.html');
const DAY=24*60*60*1000;
(async()=>{
 const browser=await chromium.launch();const page=await browser.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const fail=m=>{throw new Error(m);};
 await page.goto(URL,{waitUntil:'load'});await page.waitForTimeout(150);
 const seed=dueAt=>JSON.stringify({seeded:true,items:{bearings:{stage:0,dueAt,lapses:0,reviews:0}}});
 await page.evaluate(value=>localStorage.setItem('lsa-spaced-revision-v1',value),seed(0));
 await page.reload({waitUntil:'load'});await page.waitForTimeout(100);
 if(!(await page.locator('#btnRevisionReview').innerText()).includes('1 due'))fail('due review count was not shown in the toolbar');
 await page.click('#btnRevisionReview');
 if(!(await page.locator('#revisionReviewDialog [role="dialog"]').isVisible()))fail('recall review dialog did not open');
 if(!(await page.locator('#revisionReviewDialog').innerText()).includes('Which command prints the absolute path'))fail('scheduled learning question was not rendered');
 await page.click('[data-revision-choice="whoami"]');
 if(!(await page.locator('#revisionFeedback').innerText()).includes('Not quite'))fail('incorrect recall did not provide corrective feedback');
 let schedule=await page.evaluate(()=>JSON.parse(localStorage.getItem('lsa-spaced-revision-v1')));
 if(schedule.items.bearings.stage!==0||schedule.items.bearings.lapses!==1||schedule.items.bearings.dueAt<Date.now()+DAY-5000)fail('missed recall was not rescheduled for one day later');
 await page.click('[data-revision-next]');
 if(!(await page.locator('#revisionContent').innerText()).includes('No reviews due right now'))fail('completed due queue did not show the next scheduled review');
 await page.click('[data-revision-close]');
 await page.evaluate(value=>localStorage.setItem('lsa-spaced-revision-v1',value),seed(0));
 await page.reload({waitUntil:'load'});await page.waitForTimeout(100);
 await page.click('#btnRevisionReview');await page.click('[data-revision-choice="pwd"]');
 if(!(await page.locator('#revisionFeedback').innerText()).includes('Correct recall'))fail('correct recall was not acknowledged');
 schedule=await page.evaluate(()=>JSON.parse(localStorage.getItem('lsa-spaced-revision-v1')));
 if(schedule.items.bearings.stage!==1||schedule.items.bearings.reviews!==1||schedule.items.bearings.dueAt<Date.now()+2*DAY)fail('successful recall did not extend the review interval');
 if((await page.locator('#btnRevisionReview').innerText()).includes('due'))fail('review badge did not clear after a successful recall');
 if(errors.length)fail('Browser errors: '+errors.join('; '));
 console.log('✓ Spaced recall schedules missed concepts sooner and extends intervals after correct recall');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
