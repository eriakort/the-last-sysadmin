'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const linux = fs.readFileSync(path.join(__dirname, 'src/app.js'), 'utf8');
const network = fs.readFileSync(path.join(__dirname, 'network-trainer/ui.js'), 'utf8');
const feedback = require('./src/feedback');
assert.match(linux, /LSAFeedback\.classifyOutcome\(\{ objectiveMet: objectiveMet && masteryMet \}\)/, 'Linux mission checks use the shared outcome classifier');
assert.match(network, /F\.classifyOutcome\(/, 'Network Trainer mission checks use the shared outcome classifier');
assert.match(network, /LAST_COMMAND = \{ line, accepted: r\.code === 0 \}/, 'Network Trainer retains the latest command result');
assert.match(network, /F\.isNetworkConfigurationCommand\(last\.line\)/, 'Network Trainer uses the shared mutation-aware command classifier');
assert.match(network, /data-feedback-category=/, 'Network Trainer exposes a stable feedback category for UI verification');
assert.equal(feedback.isNetworkConfigurationCommand('ip addr add 10.0.1.10/24 dev eth0'),true,'network Linux-style configuration commands use consistent outcome feedback');
assert.equal(feedback.classifyOutcome({commandAccepted:true,configurationValid:true,objectiveMet:false}).category, 'valid-but-incorrect');
assert.equal(feedback.classifyOutcome({objectiveMet:false}).category, 'objective-unmet');
assert.equal(feedback.classifyOutcome({objectiveMet:true}).category, 'success');
assert.match(linux, /LSAFeedback\.calculateMissionReward\(S\.hints\[m\.id\] \|\| 0\)/, 'Linux mission rewards use the shared hint calculation');
assert.match(linux, /hintPenalty \? `Show hint · −\$\{hintPenalty\} XP reward`/, 'hint button explains the actual XP reward reduction');
assert.equal(feedback.calculateMissionReward(1), 100, 'one hint remains free');
assert.equal(feedback.calculateMissionReward(2), 75, 'second hint reduces the reward by 25 XP');
assert.equal(feedback.calculateMissionReward(8), 25, 'reward floor is enforced');
console.log('SHARED FEEDBACK INTEGRATION OK (12 assertions).');
