const path=require('path');
const {chromium}=require('playwright');
const URL='file://'+path.join(process.cwd(),'index.html');
(async()=>{
 const browser=await chromium.launch(),page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(URL,{waitUntil:'load'});await page.waitForTimeout(150);
 await page.evaluate(()=>{
  const linux=JSON.parse(localStorage.getItem('last-sysadmin-v1')||'{}');
  linux.done=['bearings','workspace','errors'];linux.commandSkills=['whoami','grep','pwd'];
  localStorage.setItem('last-sysadmin-v1',JSON.stringify(linux));
  const network=JSON.parse(localStorage.getItem('nettrainer')||'{}');
  network.done={'first-contact':true,'wrong-subnet':true};network.journal=[{title:'private note must not appear'}];
  localStorage.setItem('nettrainer',JSON.stringify(network));
  localStorage.setItem('nettrainer-recall-v1',JSON.stringify({'show ip route':{stage:0,dueAt:0,reviews:0,lapses:2},'show interfaces':{stage:1,dueAt:Date.now()+86400000,reviews:1,lapses:0}}));
  localStorage.setItem('lsa-cross-track-web-availability-v1',JSON.stringify({linux:true,network:true,updatedAt:new Date().toISOString()}));
  localStorage.setItem('lsa-spaced-revision-v1',JSON.stringify({seeded:true,items:{bearings:{stage:0,dueAt:0,lapses:1,reviews:0}}}));
 });
 await page.reload({waitUntil:'load'});await page.waitForTimeout(120);
 const trigger=page.locator('#btnDailyPractice');
 if(!(await trigger.isVisible()))throw new Error('daily practice entry point missing');
 await trigger.click();
 const dialog=page.locator('#dailyPracticeDialog [role="dialog"]');
 if(!(await dialog.isVisible()))throw new Error('daily practice dialog did not open');
 const body=await dialog.innerText(),normalized=body.toLocaleLowerCase();
 for(const expected of ['Daily practice','Suggested 10-minute session','Recall · Practise · Reflect','Linux administration','Network operations','Command-line skills','Integrated operations','Linux recall · 1 due','Network recall · 1 due','show ip route','2 missed recalls','Continue Linux','Open Network Sysadmin','3','2'])if(!normalized.includes(expected.toLocaleLowerCase()))throw new Error('daily practice view missing: '+expected);
 if(body.includes('private note'))throw new Error('skill map exposed private network journal content');
 if(!(await dialog.innerText()).includes('show ip route')||!(await dialog.innerText()).includes('needed extra recall practice'))throw new Error('adaptive focus did not prioritize the concept with the most recall lapses');
 const focusAction=dialog.locator('[data-dp-focus]');
 if(await focusAction.innerText()!=='Open Network Knowledge'||!(await focusAction.getAttribute('href')).includes('view=knowledge'))throw new Error('network adaptive focus did not provide a direct Knowledge action');
 if(await page.locator('.daily-practice-dialog').evaluate(el=>el.scrollWidth>el.clientWidth+2))throw new Error('daily practice dialog overflows on mobile');
 await page.click('[data-dp-close]');
 await page.evaluate(()=>{
  const network=JSON.parse(localStorage.getItem('nettrainer')||'{}');
  network.journal=[{type:'command',command:'show ip route',output:'Invalid input detected',result:'error'}];
  localStorage.setItem('nettrainer',JSON.stringify(network));
  localStorage.setItem('nettrainer-recall-v1',JSON.stringify({'show ip route':{stage:0,dueAt:0,reviews:0,lapses:0}}));
  localStorage.setItem('lsa-spaced-revision-v1',JSON.stringify({seeded:true,items:{bearings:{stage:0,dueAt:0,lapses:0,reviews:0}}}));
 });
 await page.click('#btnDailyPractice');
 if(!(await page.locator('#dailyPracticeDialog').innerText()).includes('Routing and path verification'))throw new Error('adaptive focus did not infer a routing practice recommendation from recent command errors');
 if(await page.locator('[data-dp-focus]').innerText()!=='Open Network Knowledge')throw new Error('routing recommendation did not link to Network Knowledge');

 const networkReview=page.locator('[data-dp-network-review]');
 if(!(await networkReview.getAttribute('href')).includes('view=knowledge')||!(await networkReview.getAttribute('href')).includes('dailyReview=1'))throw new Error('network recall deep link missing knowledge view or auto-review flag');
 await page.click('[data-dp-review]');
 if(!(await page.locator('#revisionReviewDialog [role="dialog"]').isVisible()))throw new Error('daily plan did not open existing spaced-recall flow');
 await page.click('[data-revision-close]');
 await page.click('#btnDailyPractice');await page.click('[data-dp-portfolio]');
 if(!(await page.locator('#portfolioDialog [role="dialog"]').isVisible()))throw new Error('daily plan did not open existing skill portfolio');
 await page.click('[data-portfolio-close]');
 if(errors.length)throw new Error('browser errors: '+errors.join('; '));
 console.log('✓ Daily practice builds a private, mobile-friendly session from existing Linux, network, command and cross-track evidence');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
