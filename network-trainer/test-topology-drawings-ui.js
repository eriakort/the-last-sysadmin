// Select, move and resize topology drawings after creation.
const path=require('path');
const {chromium,firefox,webkit}=require('playwright');
const browserName=process.env.PLAYWRIGHT_BROWSER||'chromium';
const browserType={chromium,firefox,webkit}[browserName];
if(!browserType)throw new Error('Unsupported PLAYWRIGHT_BROWSER: '+browserName);
const URL='file://'+path.join(process.cwd(),'index.html')+'?view=workbench';
(async()=>{
 const browser=await browserType.launch();
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const assert=(condition,message)=>{if(!condition)throw new Error(message);};
 await page.goto(URL,{waitUntil:'load'});
 await page.click('#btnBuild'); await page.click('#buildMenuOpen');
 await page.waitForSelector('#topo');
 const box=()=>page.locator('#topo').boundingBox();
 const point=async(rx,ry)=>{const b=await box();return{x:b.x+b.width*rx,y:b.y+b.height*ry};};
 const draw=async(tool,a,b)=>{await page.click('#config [data-draw-tool="'+tool+'"]');const p=await point(a[0],a[1]),q=await point(b[0],b[1]);await page.mouse.move(p.x,p.y);await page.mouse.down();await page.mouse.move(q.x,q.y,{steps:5});await page.mouse.up();await page.waitForTimeout(40);};
 const drag=async(locator,dx,dy)=>{const b=await locator.boundingBox();assert(!!b,'Cannot locate draggable drawing part');const x=b.x+b.width/2,y=b.y+b.height/2;await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+dx,y+dy,{steps:5});await page.mouse.up();await page.waitForTimeout(50);};
 const count=()=>page.locator('#topo .topo-drawing').count();
 await draw('arrow',[.18,.22],[.42,.32]);
 assert(await count()===1,'Arrow was not created');
 let arrow=page.locator('#topo .topo-drawing[data-drawing-index="0"]');
 let before=await arrow.evaluate(el=>['x1','y1','x2','y2'].map(k=>Number(el.getAttribute(k))));
 await drag(arrow,75,45);
 arrow=page.locator('#topo .topo-drawing[data-drawing-index="0"]');
 let moved=await arrow.evaluate(el=>['x1','y1','x2','y2'].map(k=>Number(el.getAttribute(k))));
 assert(moved[0]!==before[0]&&moved[1]!==before[1]&&moved[2]!==before[2]&&moved[3]!==before[3],'Dragging the arrow body did not move both endpoints');
 assert(await count()===1,'Moving an existing arrow created a duplicate');
 const end=page.locator('#topo .topo-drawing-handle[data-drawing-index="0"][data-drawing-handle="end"]');
 assert(await end.count()===1,'Selected arrow has no endpoint handle');
 const endBefore=await arrow.evaluate(el=>[Number(el.getAttribute('x2')),Number(el.getAttribute('y2'))]);
 await drag(end,55,25);
 arrow=page.locator('#topo .topo-drawing[data-drawing-index="0"]');
 const endAfter=await arrow.evaluate(el=>[Number(el.getAttribute('x2')),Number(el.getAttribute('y2'))]);
 assert(endAfter[0]!==endBefore[0]&&endAfter[1]!==endBefore[1],'Dragging the arrow endpoint did not resize/reposition it');
 assert(await count()===1,'Resizing an arrow created a duplicate');
 await draw('rect',[.52,.18],[.72,.38]);
 let rect=page.locator('#topo .topo-drawing[data-drawing-index="1"]');
 assert(await count()===2,'Rectangle was not created');
 const rectBefore=await rect.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 await drag(rect,45,35);
 rect=page.locator('#topo .topo-drawing[data-drawing-index="1"]');
 const rectAfter=await rect.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 assert(rectAfter[0]!==rectBefore[0]&&rectAfter[1]!==rectBefore[1],'Rectangle body did not move');
 const corner=page.locator('#topo .topo-drawing-handle[data-drawing-index="1"][data-drawing-handle="end"]');
 const widthBefore=await rect.getAttribute('width');
 await drag(corner,35,20);
 rect=page.locator('#topo .topo-drawing[data-drawing-index="1"]');
 assert(await rect.getAttribute('width')!==widthBefore,'Rectangle resize handle did not change its dimensions');
 await draw('ellipse',[.18,.55],[.35,.72]);
 await draw('freehand',[.48,.58],[.62,.68]);
 assert(await count()===4,'Ellipse or freehand drawing was not created');
 const freehand=page.locator('#topo .topo-drawing[data-drawing-index="3"]');
 const pathBefore=await freehand.getAttribute('d');
 await drag(freehand,40,30);
 const pathAfter=await page.locator('#topo .topo-drawing[data-drawing-index="3"]').getAttribute('d');
 assert(pathAfter!==pathBefore,'Freehand drawing did not move as a whole');
 assert(await count()===4,'Editing existing drawings created additional drawings');
 page.once('dialog',d=>d.accept('Movable note'));await page.click('#noteBtn');
 const note=page.locator('#topo .topo-note').first();await note.waitFor();
 const noteBefore=await note.getAttribute('transform');await drag(note,50,35);
 const noteAfter=await page.locator('#topo .topo-note').first().getAttribute('transform');
 assert(noteAfter!==noteBefore,'Topology note could not be repositioned');
 if(errors.length)throw new Error(errors.join(' | '));
 await browser.close();
 console.log('TOPOLOGY DRAWING EDIT UI TEST OK ('+browserName+').');
})().catch(e=>{console.error(e);process.exit(1);});
