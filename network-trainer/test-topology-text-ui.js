// Editable, independently movable topology labels and free canvas text.
const path=require('path');
const {chromium,firefox,webkit}=require('playwright');
const browserName=process.env.PLAYWRIGHT_BROWSER||'chromium';
const browserType={chromium,firefox,webkit}[browserName];
if(!browserType)throw new Error('Unsupported PLAYWRIGHT_BROWSER: '+browserName);
const URL='file://'+path.join(process.cwd(),'index.html')+'?view=workbench';
(async()=>{
 const browser=await browserType.launch();
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const ok=m=>console.log('  ✓ '+m);
 const assert=(condition,message)=>{if(!condition)throw new Error(message);};
 await page.goto(URL,{waitUntil:'load'});
 await page.click('#btnBuild');
 await page.waitForSelector('#config .pal[data-add="host"]');
 await page.click('#config .pal[data-add="host"]');
 await page.waitForSelector('#topo .device-label[data-label-kind="name"]');
 const name=page.locator('#topo .device-label[data-label-kind="name"]');
 const type=page.locator('#topo .device-label[data-label-kind="type"]');
 assert(await name.evaluate(el=>!el.closest('.node')),'Device name label is still nested inside the device icon group');
 assert(await type.evaluate(el=>!el.closest('.node')),'Device type label is still nested inside the device icon group');
 const node=page.locator('#topo .node[data-dev="h1"]');
 const transformBefore=await node.getAttribute('transform');
 const nameBefore=await name.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 const nameBox=await name.boundingBox();
 await page.mouse.move(nameBox.x+nameBox.width/2,nameBox.y+nameBox.height/2);
 await page.mouse.down();
 await page.mouse.move(nameBox.x+nameBox.width/2+75,nameBox.y+nameBox.height/2+38,{steps:6});
 await page.mouse.up();
 await page.waitForTimeout(50);
 const movedName=page.locator('#topo .device-label[data-label-kind="name"]');
 const nameAfter=await movedName.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 assert(nameAfter[0]!==nameBefore[0]||nameAfter[1]!==nameBefore[1],'Dragging the device name label did not move it');
 assert(await node.getAttribute('transform')===transformBefore,'Dragging a device label moved the device icon');
 ok('device name label moves independently from its icon');
 await movedName.click({button:'right'});
 await page.waitForSelector('.topo-context-menu [data-action="edit-device-label"]');
 page.once('dialog',d=>d.accept('Gateway'));
 await page.locator('.topo-context-menu [data-action="edit-device-label"]').click();
 await page.waitForFunction(()=>document.querySelector('#topo .name-label')?.textContent==='Gateway');
 await page.locator('#topo .device-label[data-label-kind="type"]').click({button:'right'});
 await page.waitForSelector('.topo-context-menu [data-action="edit-device-label"]');
 page.once('dialog',d=>d.accept('Edge router'));
 await page.locator('.topo-context-menu [data-action="edit-device-label"]').click();
 await page.waitForFunction(()=>document.querySelector('#topo .type-label')?.textContent==='Edge router');
 ok('device name and type labels are independently editable');
 await page.click('#textBtn');
 const svgBox=await page.locator('#topo').boundingBox();
 page.once('dialog',d=>d.accept('WAN handoff'));
 await page.mouse.click(svgBox.x+svgBox.width*.55,svgBox.y+svgBox.height*.55);
 const freeText=page.locator('#topo .topo-text').first();
 await freeText.waitFor();
 assert(await freeText.textContent()==='WAN handoff','Canvas text was not inserted at the clicked location');
 const textBefore=await freeText.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 const textBox=await freeText.boundingBox();
 await page.mouse.move(textBox.x+textBox.width/2,textBox.y+textBox.height/2);
 await page.mouse.down();
 await page.mouse.move(textBox.x+textBox.width/2+52,textBox.y+textBox.height/2+24,{steps:5});
 await page.mouse.up();
 await page.waitForTimeout(50);
 const movedText=page.locator('#topo .topo-text').first();
 const textAfter=await movedText.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 assert(textAfter[0]!==textBefore[0]||textAfter[1]!==textBefore[1],'Free canvas text did not move');
 ok('free text can be placed anywhere and moved independently');
 await movedText.focus();
 page.once('dialog',d=>d.accept('WAN edge'));
 await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('#topo .topo-text')?.textContent==='WAN edge');
 await page.locator('#topo .topo-text').focus();
 await page.keyboard.press('ArrowRight');
 const keyboardMoved=await page.locator('#topo .topo-text').evaluate(el=>Number(el.getAttribute('x')));
 assert(keyboardMoved===textAfter[0]+10,'ArrowRight did not move selected free text by 10 canvas units');
 ok('free text supports editing and keyboard repositioning');
 await page.reload({waitUntil:'load'});
 await page.waitForSelector('#topo .device-label[data-label-kind="name"]');
 assert(await page.locator('#topo .name-label').textContent()==='Gateway','Edited device name did not persist after refresh');
 assert(await page.locator('#topo .type-label').textContent()==='Edge router','Edited device type did not persist after refresh');
 const restoredName=await page.locator('#topo .name-label').evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 assert(restoredName[0]===nameAfter[0]&&restoredName[1]===nameAfter[1],'Independent device label position did not persist after refresh');
 assert(await page.locator('#topo .topo-text').first().textContent()==='WAN edge','Free text did not persist after refresh');
 ok('edited labels, independent positions and free text persist in the Build draft');
 await page.locator('#topo .topo-text').first().click({button:'right'});
 await page.waitForSelector('.topo-context-menu');
 await page.locator('.topo-context-menu [data-action="delete-text"]').click();
 assert(await page.locator('#topo .topo-text').count()===0,'Canvas text context-menu delete failed');
 if(errors.length)throw new Error(errors.join(' | '));
 await browser.close();
 console.log('TOPOLOGY TEXT UI TEST OK ('+browserName+').');
})().catch(e=>{console.error(e);process.exit(1);});
