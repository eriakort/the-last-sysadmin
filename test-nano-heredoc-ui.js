const path=require('path');
const {chromium}=require('playwright');
const URL='file://'+path.join(process.cwd(),'index.html');
(async()=>{
 const browser=await chromium.launch();const page=await browser.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(URL,{waitUntil:'load'});await page.waitForTimeout(200);
 const command=async value=>{await page.locator('#tin').fill(value);await page.locator('#tin').press('Enter');await page.waitForTimeout(80);};
 await command('nano /home/rookie/nano-batch-d.txt');
 const editor=page.locator('.nano-editor');
 if(!(await editor.isVisible()))throw new Error('nano did not open the editor');
 await editor.fill('Saved from the simulated editor\nsecond line\n');
 await editor.press('Control+s');
 if(!(await page.locator('.nano-status[data-state="saved"]').count()))throw new Error('nano did not report a successful save');
 await page.locator('.nano-actions button').filter({hasText:'Exit without saving'}).click();
 await command('cat /home/rookie/nano-batch-d.txt');
 if(!(await page.locator('#tout').innerText()).includes('Saved from the simulated editor'))throw new Error('nano changes were not written to the virtual filesystem');
 await command('cat <<END > /home/rookie/heredoc-unquoted.txt');
 await page.locator('#tin').fill('hello $USER');await page.locator('#tin').press('Enter');
 await page.locator('#tin').fill('END');await page.locator('#tin').press('Enter');await page.waitForTimeout(100);
 await command('cat /home/rookie/heredoc-unquoted.txt');
 if(!(await page.locator('#tout').innerText()).includes('hello rookie'))throw new Error('unquoted heredoc did not expand $USER');
 await command("cat <<'END' > /home/rookie/heredoc-quoted.txt");
 await page.locator('#tin').fill('hello $USER');await page.locator('#tin').press('Enter');
 await page.locator('#tin').fill('END');await page.locator('#tin').press('Enter');await page.waitForTimeout(100);
 await command('cat /home/rookie/heredoc-quoted.txt');
 if(!(await page.locator('#tout').innerText()).includes('hello $USER'))throw new Error('quoted heredoc did not preserve literal variable text');
 if(errors.length)throw new Error('Browser errors: '+errors.join('; '));
 console.log('✓ nano saves files and heredocs preserve quoted text / expand unquoted variables');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
