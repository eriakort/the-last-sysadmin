// Editable, independently movable topology labels and free canvas text.
const path=require('path');
const {chromium,firefox,webkit}=require('playwright');
const browserName=process.env.PLAYWRIGHT_BROWSER||'chromium';
const browserType={chromium,firefox,webkit}[browserName];
if(!browserType)throw new Error('Unsupported PLAYWRIGHT_BROWSER: '+browserName);
const URL='file://'+path.join(process.cwd(),'index.html')+'?view=workbench';
(async()=>{
 const browser=await browserType.launch();
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const ok=m=>console.log('  ✓ '+m);
 const assert=(condition,message)=>{if(!condition)throw new Error(message);};
 await page.goto(URL,{waitUntil:'load'});
 await page.click('#btnBuild');
 await page.waitForSelector('#config .pal[data-add="host"]');
 await page.click('#config .pal[data-add="host"]');
 await page.waitForSelector('#topo .device-label[data-label-kind="name"]');
 const name=page.locator('#topo .device-label[data-label-kind="name"]');
 const type=page.locator('#topo .device-label[data-label-kind="type"]');
 assert(await name.evaluate(el=>!el.closest('.node')),'Device name label is still nested inside the device icon group');
 assert(await type.evaluate(el=>!el.closest('.node')),'Device type label is still nested inside the device icon group');
 const node=page.locator('#topo .node[data-dev="h1"]');
 const transformBefore=await node.getAttribute('transform');
 const nameBefore=await name.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 const nameBox=await name.boundingBox();
 const nx=nameBox.x+nameBox.width/2, ny=nameBox.y+nameBox.height/2;
 await page.evaluate(({x,y,dx,dy})=>{
   const target=document.elementFromPoint(x,y)||document.querySelector('#topo');
   const fire=(type,cx,cy,el)=>{el.dispatchEvent(new PointerEvent(type,{bubbles:true,cancelable:true,clientX:cx,clientY:cy,pointerId:1,pointerType:'mouse',button:0,buttons:type==='pointerup'?0:1}));};
   fire('pointerdown',x,y,target);
   fire('pointermove',x+dx,y+dy,document);
   fire('pointerup',x+dx,y+dy,document);
 },{x:nx,y:ny,dx:160,dy:90});
 await page.waitForTimeout(50);
 let movedName=page.locator('#topo .device-label[data-label-kind="name"]');
 let nameAfter=await movedName.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 if(nameAfter[0]===nameBefore[0]&&nameAfter[1]===nameBefore[1]){
   await movedName.focus();
   await page.keyboard.press('ArrowRight');
   await page.waitForTimeout(30);
   movedName=page.locator('#topo .device-label[data-label-kind="name"]');
   nameAfter=await movedName.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 }
 assert(nameAfter[0]!==nameBefore[0]||nameAfter[1]!==nameBefore[1],'Device name label did not move by pointer drag or keyboard');
 assert(await node.getAttribute('transform')===transformBefore,'Dragging a device label moved the device icon');
 ok('device name label moves independently from its icon');
 await movedName.focus();
 await page.keyboard.press('Shift+F10');
 await page.waitForSelector('.topo-context-menu [data-action="edit-device-label"]');
 page.once('dialog',d=>d.accept('Gateway'));
 await page.locator('.topo-context-menu [data-action="edit-device-label"]').click();
 await page.waitForFunction(()=>document.querySelector('#topo .name-label')?.textContent==='Gateway');
 await page.locator('#topo .device-label[data-label-kind="type"]').focus();
 await page.keyboard.press('Shift+F10');
 await page.waitForSelector('.topo-context-menu [data-action="edit-device-label"]');
 page.once('dialog',d=>d.accept('Edge router'));
 await page.locator('.topo-context-menu [data-action="edit-device-label"]').click();
 await page.waitForFunction(()=>document.querySelector('#topo .type-label')?.textContent==='Edge router');
 ok('device name and type labels are independently editable');
 // Device labels are removed independently, then can be restored from the device menu.
 await page.locator('#topo .name-label').focus(); await page.keyboard.press('Shift+F10');
 await page.locator('.topo-context-menu [data-action="clear-device-label"]').click();
 assert(await page.locator('#topo .name-label').count()===0,'Delete label should hide the selected device label');
 await page.locator('#topo .node[data-dev="h1"]').click({button:'right'});
 await page.waitForSelector('.topo-context-menu [data-action="restore-device-label-name"]');
 await page.locator('.topo-context-menu [data-action="restore-device-label-name"]').click();
 assert(await page.locator('#topo .name-label').count()===1,'Device context menu should restore a deleted label');
 ok('device labels can be deleted and restored independently');
 // Drag the visible resize handles; size changes must not move the device or its label.
 const labelResize=page.locator('#topo .topo-label-resize[data-label-kind="name"]');
 const labelSizeBefore=Number(await page.locator('#topo .name-label').getAttribute('font-size'));
 const labelHandleBox=await labelResize.boundingBox();
 await page.mouse.move(labelHandleBox.x+labelHandleBox.width/2,labelHandleBox.y+labelHandleBox.height/2);
 await page.mouse.down(); await page.mouse.move(labelHandleBox.x+labelHandleBox.width/2+35,labelHandleBox.y+labelHandleBox.height/2); await page.mouse.up();
 const labelSizeAfter=Number(await page.locator('#topo .name-label').getAttribute('font-size'));
 assert(labelSizeAfter>labelSizeBefore,'Dragging label resize handle did not increase label font size');
 const deviceArt=page.locator('#topo .node[data-dev="h1"] .device-art-scale');
 const deviceScaleBefore=await deviceArt.getAttribute('transform');
 const deviceHandle=page.locator('#topo .topo-device-resize[data-dev="h1"]');
 const deviceHandleBox=await deviceHandle.boundingBox();
 await page.mouse.move(deviceHandleBox.x+deviceHandleBox.width/2,deviceHandleBox.y+deviceHandleBox.height/2);
 await page.mouse.down(); await page.mouse.move(deviceHandleBox.x+deviceHandleBox.width/2+42,deviceHandleBox.y+deviceHandleBox.height/2); await page.mouse.up();
 const deviceScaleAfter=await page.locator('#topo .node[data-dev="h1"] .device-art-scale').getAttribute('transform');
 assert(deviceScaleAfter!==deviceScaleBefore,'Dragging device resize handle did not resize device artwork');
 ok('device artwork and device labels resize independently');
 await page.click('#textBtn');
 const svgBox=await page.locator('#topo').boundingBox();
 page.once('dialog',d=>d.accept('WAN handoff'));
 await page.mouse.click(svgBox.x+svgBox.width*.55,svgBox.y+svgBox.height*.55);
 const freeText=page.locator('#topo .topo-text').first();
 await freeText.waitFor();
 assert(await freeText.textContent()==='WAN handoff','Canvas text was not inserted at the clicked location');
 const textBefore=await freeText.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 const textBox=await freeText.boundingBox();
 const tx=textBox.x+textBox.width/2, ty=textBox.y+textBox.height/2;
 await page.evaluate(({x,y,dx,dy})=>{
   const target=document.elementFromPoint(x,y)||document.querySelector('#topo');
   const fire=(type,cx,cy,el)=>{el.dispatchEvent(new PointerEvent(type,{bubbles:true,cancelable:true,clientX:cx,clientY:cy,pointerId:1,pointerType:'mouse',button:0,buttons:type==='pointerup'?0:1}));};
   fire('pointerdown',x,y,target);
   fire('pointermove',x+dx,y+dy,document);
   fire('pointerup',x+dx,y+dy,document);
 },{x:tx,y:ty,dx:120,dy:60});
 await page.waitForTimeout(50);
 let movedText=page.locator('#topo .topo-text').first();
 let textAfter=await movedText.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 if(textAfter[0]===textBefore[0]&&textAfter[1]===textBefore[1]){
   await movedText.focus();
   await page.keyboard.press('ArrowRight');
   await page.waitForTimeout(30);
   movedText=page.locator('#topo .topo-text').first();
   textAfter=await movedText.evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 }
 assert(textAfter[0]!==textBefore[0]||textAfter[1]!==textBefore[1],'Free canvas text did not move by pointer drag or keyboard');
 ok('free text can be placed anywhere and moved independently');
 await movedText.focus();
 page.once('dialog',d=>d.accept('WAN edge'));
 await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('#topo .topo-text')?.textContent==='WAN edge');
 await page.locator('#topo .topo-text').focus();
 await page.keyboard.press('ArrowRight');
 const keyboardMoved=await page.locator('#topo .topo-text').evaluate(el=>Number(el.getAttribute('x')));
 assert(keyboardMoved===textAfter[0]+10,'ArrowRight did not move selected free text by 10 canvas units');
 ok('free text supports editing and keyboard repositioning');
 await page.reload({waitUntil:'load'});
 await page.waitForSelector('#topo .device-label[data-label-kind="name"]');
 assert(await page.locator('#topo .name-label').textContent()==='Gateway','Edited device name did not persist after refresh');
 assert(await page.locator('#topo .type-label').textContent()==='Edge router','Edited device type did not persist after refresh');
 const editableName=page.locator('#topo .name-label'); await editableName.focus(); await page.keyboard.press('Delete');
 assert(await page.locator('#topo .name-label').textContent()==='h1','Delete key did not reset a custom device name label');
 const restoredName=await page.locator('#topo .name-label').evaluate(el=>[Number(el.getAttribute('x')),Number(el.getAttribute('y'))]);
 assert(restoredName[0]===nameAfter[0]&&restoredName[1]===nameAfter[1],'Independent device label position did not persist after refresh');
 assert(await page.locator('#topo .topo-text').first().textContent()==='WAN edge','Free text did not persist after refresh');
 ok('edited labels, independent positions and free text persist in the Build draft');
 await page.locator('#topo .topo-text').first().focus();
 await page.keyboard.press('Shift+F10');
 await page.waitForSelector('.topo-context-menu');
 await page.locator('.topo-context-menu [data-action="delete-text"]').click();
 assert(await page.locator('#topo .topo-text').count()===0,'Canvas text context-menu delete failed');
 page.once('dialog',d=>d.accept('Delete me'));
 await page.locator('#topo').click({button:'right',position:{x:24,y:24}});
 await page.locator('.topo-context-menu [data-action="add-text"]').click();
 const deletable=page.locator('#topo .topo-text').first(); await deletable.waitFor();
 await deletable.focus(); await page.keyboard.press('Delete');
 assert(await page.locator('#topo .topo-text').count()===0,'Delete key did not remove focused canvas text');
 if(errors.length)throw new Error(errors.join(' | '));
 await browser.close();
 console.log('TOPOLOGY TEXT UI TEST OK ('+browserName+').');
})().catch(e=>{console.error(e);process.exit(1);});
